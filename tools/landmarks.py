#!/usr/bin/env python3
"""Pick one landmark quest per story script, then write the ledger probe script.

One landmark per story answers "has this account done this story" with one quest value.
The last quest a story script completes is the story's finish line, so that is the
landmark. The client can read a quest's state from the game with
`world.getQuestValue(slot)`, which is how the library's own checks work
(CoreBots.cs:4890 `isCompletedBefore`).

Usage:
    python tools/landmarks.py --scripts "%APPDATA%/VibeSkua/Scripts" --out landmarks.json
    python tools/landmarks.py --scripts ... --emit-script AgentStoryLedger.cs
"""
from __future__ import annotations

import argparse
import json
import os
import re
from pathlib import Path

COMPLETE_CALL = re.compile(r"\b(?:EnsureComplete|Complete)\(\s*(\d{3,6})\b")
HEADER = re.compile(r"/\*(.*?)\*/", re.DOTALL)

SCRIPT_TEMPLATE = '''/*
name: Agent Story Ledger
description: Reads one landmark quest per story and logs done or todo for each, so two accounts can be compared. Free to play, no fighting, no gold spent. About 2 minutes per account.
tags: agent, story, ledger, probe, campaign
version: 0.1
*/
//cs_include Scripts/CoreBots.cs
using Skua.Core.Interfaces;
using Skua.Core.Models.Quests;

public class AgentStoryLedger
{
    public IScriptInterface Bot => IScriptInterface.Instance;
    public CoreBots Core => CoreBots.Instance;

    // story name -> landmark quest id. Generated by tools/landmarks.py.
    private static readonly (string Story, int QuestId)[] Landmarks = new[]
    {
{ROWS}
    };

    public void ScriptMain(IScriptInterface bot)
    {
        Core.Logger($"LEDGER|start|{Landmarks.Length} landmarks");
        int doneCount = 0;

        foreach ((string story, int questId) in Landmarks)
        {
            string state = "error";
            try
            {
                Quest quest = Bot.Quests.EnsureLoad(questId);
                bool done = quest != null && (quest.Slot < 0
                    || Bot.Flash.CallGameFunction<int>("world.getQuestValue", quest.Slot) >= quest.Value);
                state = done ? "done" : "todo";
                if (done)
                    doneCount++;
            }
            catch (System.Exception e)
            {
                state = $"error:{e.GetType().Name}";
            }
            Core.Logger($"LEDGER|{state}|{questId}|{story}");
        }

        Core.Logger($"LEDGER|summary|{doneCount}/{Landmarks.Length} stories done");
    }
}
'''


def header_name(path: Path) -> str:
    text = path.read_text(encoding="utf-8-sig", errors="ignore")
    match = HEADER.search(text)
    if match:
        for line in match.group(1).splitlines():
            if line.strip().startswith("name:"):
                return line.split(":", 1)[1].strip()
    return path.stem


def landmarks(scripts_root: Path, folders: list[str], cap: int) -> list[dict]:
    out: list[dict] = []
    for folder in folders:
        root = scripts_root / folder
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.cs")):
            ids = COMPLETE_CALL.findall(path.read_text(encoding="utf-8-sig", errors="ignore"))
            if not ids:
                continue
            out.append({"story": header_name(path), "questId": int(ids[-1]),
                        "script": path.relative_to(scripts_root).as_posix()})
    out.sort(key=lambda row: row["story"].lower())
    return out[:cap] if cap else out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scripts", required=True)
    ap.add_argument("--folders", default="Story")
    ap.add_argument("--out", default="")
    ap.add_argument("--cap", type=int, default=0, help="keep at most N landmarks")
    ap.add_argument("--emit-script", default="", help="write this probe script here")
    args = ap.parse_args()

    root = Path(os.path.expandvars(args.scripts))
    if not root.is_dir():
        print(f"missing scripts folder {root}")
        return 1
    rows = landmarks(root, [f.strip() for f in args.folders.split(",") if f.strip()], args.cap)
    print(f"{len(rows)} landmarks from {args.folders}")

    if args.out:
        Path(args.out).write_text(json.dumps(rows, indent=1), encoding="utf-8")
        print(f"wrote {args.out}")

    if args.emit_script:
        body = ",\n".join(
            f'        ("{row["story"].replace(chr(34), "")}", {row["questId"]})' for row in rows
        )
        target = Path(args.emit_script)
        target.write_text(SCRIPT_TEMPLATE.replace("{ROWS}", body), encoding="utf-8")
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
